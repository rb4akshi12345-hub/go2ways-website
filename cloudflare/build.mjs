// Build for Cloudflare Pages: copies only the public website into dist/ and bundles the
// assistant's company briefing for the chat function.
//   npm run build        (Cloudflare runs this automatically)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist);

// Public pages
let pages = 0;
for (const f of fs.readdirSync(root)) {
  if (f.endsWith(".html")) { fs.copyFileSync(path.join(root, f), path.join(dist, f)); pages++; }
}

// Public assets (skip notes like CREDITS.md)
let assets = 0;
function copyDir(from, to) {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || entry.name.endsWith(".md")) continue;
    const a = path.join(from, entry.name), b = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(a, b); else { fs.copyFileSync(a, b); assets++; }
  }
}
copyDir(path.join(root, "assets"), path.join(dist, "assets"));

// Security headers for every page
fs.writeFileSync(path.join(dist, "_headers"), `/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
`);

// The chat function reads the company briefing from this generated module.
const knowledge = fs.readFileSync(path.join(root, "server", "knowledge.md"), "utf8");
fs.writeFileSync(
  path.join(root, "cloudflare", "knowledge.js"),
  "// Generated by cloudflare/build.mjs from server/knowledge.md. Edit that file, not this one.\n" +
  `export const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`,
);

console.log(`Built dist/: ${pages} pages, ${assets} asset files. Chat briefing bundled.`);
